#!/usr/bin/env python3
"""Write a VHS tape (https://github.com/charmbracelet/vhs) that records a demo
race, plus a made-up race history so the results screen has averages to show.

    python3 tools/demo.py demo.tape /tmp/typerace-demo
    vhs demo.tape                        # -> docs/demo.gif

The demo workflow (.github/workflows/demo.yml) runs this in GitHub Actions.
"""
import csv
import datetime as dt
import os
import random
import sys
import tempfile

tape_path, data_dir = sys.argv[1], os.path.abspath(sys.argv[2])
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))
os.environ["XDG_DATA_HOME"] = tempfile.mkdtemp()     # scratch: picking writes seen.json
from typerace import app  # noqa: E402

quotes = app.all_quotes()


def first_quote(seed):
    """The quote `TYPERACE_SEED=seed typerace medium` starts with on fresh data."""
    if os.path.exists(app.SEEN_FILE):
        os.remove(app.SEEN_FILE)                     # each trial starts fresh, like the demo
    random.seed(str(seed))
    return app.Picker(quotes, "medium").next()


# a medium quote that's quick to watch and easy to put in a VHS string
for seed in range(1, 5000):
    text, source = first_quote(seed)
    if 130 <= len(text) <= 175 and not any(c in text for c in "\"'`\\$") and "," in text:
        break
print(f"seed {seed}: {text!r} ({source})")

# a plausible history: ~40 earlier races, improving slowly
os.makedirs(os.path.join(data_dir, "typerace"), exist_ok=True)
rng = random.Random(7)
start = dt.datetime(2026, 9, 1, 18, 0)
with open(os.path.join(data_dir, "typerace", "history.csv"), "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["date", "wpm", "accuracy", "seconds", "quote_by"])
    for i in range(40):
        when = start + dt.timedelta(hours=i * 7)
        w.writerow([when.isoformat(timespec="seconds"), f"{rng.gauss(84 + i * 0.35, 7):.1f}",
                    f"{rng.uniform(93, 99.5):.1f}", f"{rng.uniform(15, 45):.1f}", "earlier race"])

# the tape: type word by word at a human, uneven pace, with two typos fixed
# by backspace and one word cleared with ctrl+w
words = text.split(" ")
typo_at = set(rng.sample(range(2, len(words) - 2), 2))
clear_at = rng.choice([i for i in range(3, len(words) - 1) if i not in typo_at])
lines = [
    'Output docs/demo.gif',
    'Set Shell "bash"',
    'Set FontSize 16',
    'Set Width 1100',
    'Set Height 880',
    'Set Padding 24',
    'Set Theme "nord"',
    'Set WindowBar Colorful',
    'Set CursorBlink false',
    f'Env XDG_DATA_HOME "{data_dir}"',
    f'Env TYPERACE_SEED "{seed}"',
    'Hide',
    'Type "clear"',
    'Enter',
    'Show',
    'Sleep 500ms',
    'Type@70ms "typerace medium"',
    'Sleep 400ms',
    'Enter',
    'Sleep 1.8s',
]
for i, word in enumerate(words):
    piece = word + (" " if i < len(words) - 1 else "")
    speed = rng.randint(55, 105)
    if i in typo_at and len(word) > 2:
        k = rng.randint(1, len(word) - 1)
        wrong = "x" if word[k].lower() != "x" else "z"
        lines += [f'Type@{speed}ms "{word[:k]}{wrong}"', 'Sleep 350ms', 'Backspace', 'Sleep 120ms',
                  f'Type@{speed}ms "{piece[k:]}"']
    elif i == clear_at:
        lines += [f'Type@{speed}ms "{word[:2]}qw"', 'Sleep 300ms', 'Ctrl+W', 'Sleep 200ms',
                  f'Type@{speed}ms "{piece}"']
    else:
        lines.append(f'Type@{speed}ms "{piece}"')
    if rng.random() < 0.15:
        lines.append(f'Sleep {rng.randint(150, 450)}ms')
lines += ['Sleep 7s']

with open(tape_path, "w") as f:
    f.write("# generated by tools/demo.py\n" + "\n".join(lines) + "\n")
print(f"wrote {tape_path} ({len(lines)} commands), history in {data_dir}")
